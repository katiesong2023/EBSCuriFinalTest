function expansionAnchors(standard) {
  const metadata = standard?.metadata || {};
  const match = /^(4[사과]|9과|9사\((?:지리|일사)\))(\d{2})-\d{2}$/.exec(metadata.achievementStandardId || "");
  if (!match || (match[1].includes("사") ? "사회" : "과학") !== metadata.subject) return null;
  const key = `${match[1]}${match[2]}`, vocabulary = unitAnchors[key];
  if (!vocabulary) return null;
  const text = String(metadata.achievementStandard || "").normalize("NFKC");
  const literal = (term) => text.includes(term.normalize("NFKC"));
  let anchors = vocabulary.filter(literal);
  // 예상과 다른 원문은 같은 교과의 검토된 구체 어휘만 재사용한다. 수행 동사·어미로 후보 수를 채우지 않는다.
  if (!anchors.length) anchors = [...new Set(Object.entries(unitAnchors)
    .filter(([unit]) => (unit.includes("사") ? "사회" : "과학") === metadata.subject)
    .flatMap(([, terms]) => terms))].filter(literal);
  return { terms: [...anchors], anchors };
}

module.exports = { expansionAnchors, unitAnchors };
