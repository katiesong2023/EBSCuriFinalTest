const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
(async()=>{
  const base=process.env.CURI_TEST_URL || 'http://127.0.0.1:3000';
  const before=JSON.parse(await fs.readFile('docs/r12-33-related-before.json'));
  const sample=before.rows.find(row=>row.title==='내 몸속의 돌, 결석');
  const {chromium}=require('/Users/yunseo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
  const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  const cases=[],errors=[];
  try{
    const page=await browser.newPage({viewport:{width:390,height:900}});page.setDefaultTimeout(60000);
    page.on('pageerror',e=>errors.push(e.message));
    await page.route('**/*',route=>route.request().url().includes('/api/curi/discover/thumbnail?')?route.fulfill({status:404,body:''}):route.request().url().startsWith(base)?route.continue():route.abort());
    // 기존에 다른 검색어로 저장한 자료를 현재 검색 결과에서 다시 가져오는 경우.
    await page.addInitScript(resource=>localStorage.setItem('curi.discovery.shelf.v1',JSON.stringify([{...resource,query:'인구 분포'}])),sample);
    await page.goto(base+'/?'+new URLSearchParams({q:'인체'}));
    const card=page.locator(`[data-id="${sample.id}"]`).first();await card.waitFor();
    const response=page.waitForResponse(r=>r.url().includes('/api/curi/curriculum/related'));
    await card.locator('[data-folder-save]').click();
    const relatedResponse=await response, request=relatedResponse.request().postDataJSON(), data=await relatedResponse.json();
    assert.equal(relatedResponse.request().method(),'POST');
    assert.equal(relatedResponse.status(),200);assert.equal(request.searchQuery,'인체');
    assert.ok(request.summary.includes('요로결석'));
    const dialog=page.locator('#folder-picker-dialog');
    await dialog.locator('[data-options] input').first().waitFor();
    const displayed=await dialog.locator('[data-options] input').evaluateAll(els=>els.map(el=>el.value));
    assert.deepEqual(displayed,data.related.map(x=>x.id));assert.ok(['6과04-02','6과04-03'].includes(displayed[0]));
    assert.ok(!displayed.some(id=>['4사10-02','6사02-02','6사12-01'].includes(id)));
    cases.push('현재 검색어 전달·기존 저장 검색어보다 현재 요청 우선');
    cases.push('건강 기준 상단·API 관련도 순서를 모바일에 유지');
    await dialog.locator('[data-options] input').nth(0).check();await dialog.locator('[data-options] input').nth(1).check();
    assert.equal(await dialog.locator('[data-bring-page="1"]').isVisible(),true);
    await dialog.locator('[data-all]').click();assert.equal(await dialog.locator('[data-options] input').count(),214);
    await dialog.locator('[data-related]').click();assert.deepEqual(await dialog.locator('[data-options] input').evaluateAll(els=>els.map(el=>el.value)),displayed);
    assert.equal(await dialog.locator('[data-options] input:checked').count(),2);
    await page.screenshot({path:'docs/r12-34-related-ranked-390.png'});
    await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:'docs/r12-34-related-ranked-1440.png'});
    await dialog.locator('[data-skip]').click();assert.match(await dialog.locator('#folder-picker-selection').innerText(),/2개 선택/);
    await dialog.locator('[data-back]').click();assert.equal(await dialog.locator('[data-options] input:checked').count(),2);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    cases.push('다중 선택·전체214보기·관련 순서 복원·단계 이동 보존');
    await dialog.locator('[data-close]').click();
    const fallbackResponse=page.waitForResponse(r=>r.url().includes('/api/curi/curriculum/related'));
    await page.evaluate(resource=>{const host=document.createElement('div');host.id='saved-context-audit';document.body.append(host);CuriTeacher.curriculumSelection.mount(host,{resource:{...resource,query:'인구 분포'}});},sample);
    assert.equal((await fallbackResponse).request().postDataJSON().searchQuery,'인구 분포');
    cases.push('저장 자료의 선택기에서는 저장된 검색어 재사용');
    const longSummary='방송 제작 배경을 소개합니다. '.repeat(80)+'이주 배경 어린이들이 서로 다른 문화를 존중하는 교실이다.';
    const longResponse=page.waitForResponse(r=>r.url().includes('/api/curi/curriculum/related'));
    await page.evaluate(summary=>{const host=document.createElement('div');host.id='full-content-audit';document.body.append(host);CuriTeacher.curriculumSelection.mount(host,{resource:{title:'함께 배우는 교실',summary},searchQuery:'다문화'});},longSummary);
    const full=await longResponse;
    assert.equal(full.request().postDataJSON().summary,longSummary);
    const fullData=await full.json();assert.ok(fullData.related.some(x=>x.id==='4사03-02'));
    assert.ok(fullData.related.find(x=>x.id==='4사03-02').evidence.some(e=>e.start>200));
    await page.locator('#full-content-audit [data-options] input').first().waitFor();
    cases.push('소개문 전체 POST·200자 뒤 문화 다양성 후보·원문 근거');
    assert.deepEqual(errors,[]);
    await fs.writeFile('docs/r12-34-related-context-browser-check.json',JSON.stringify({checkedAt:new Date().toISOString(),cases,passed:cases.length,resourceId:sample.id,searchQuery:'인체',apiOrder:data.related.map(x=>x.id),displayedOrder:displayed,errors,paidApiCalls:0},null,2)+'\n');
    console.log(cases.length,'관련 교육과정 브라우저 검증 통과');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
